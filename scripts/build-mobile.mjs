import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import ts from "typescript";

const root = process.cwd();

function loadTsModule(relPath, injectedExports = {}) {
  const fullPath = path.join(root, relPath);
  const source = fs.readFileSync(fullPath, "utf8");
  const transpiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
  }).outputText;

  const mod = { exports: {} };
  const sandbox = {
    module: mod,
    exports: mod.exports,
    require: (id) => {
      if (injectedExports[id]) return injectedExports[id];
      return {};
    },
  };
  vm.runInNewContext(transpiled, sandbox, { filename: relPath });
  return mod.exports;
}

const extMod = loadTsModule("src/lib/data/verified-seed-extended.ts");
const coreMod = loadTsModule("src/lib/data/verified-seed.ts", {
  "./verified-seed-extended": extMod,
});

const allSeeds = coreMod.VERIFIED_SEED_ASSETS || [];
if (!Array.isArray(allSeeds) || allSeeds.length < 90) {
  console.error("Failed to extract VERIFIED_SEED_ASSETS, got:", allSeeds.length);
  process.exit(1);
}

const outPath = path.join(root, "mobile", "seed-data.js");
const jsPayload = `// Auto-generated by scripts/build-mobile.mjs — DO NOT EDIT MANUALLY\nwindow.HCI_SEED_ASSETS = ${JSON.stringify(allSeeds)};\n`;
fs.writeFileSync(outPath, jsPayload, "utf8");
console.log(`Generated mobile/seed-data.js with ${allSeeds.length} verified Spot asset profiles.`);
