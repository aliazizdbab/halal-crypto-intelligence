      catalystsEn: `Protocol upgrades and developer/enterprise integrations across ${s.name}.`,
      catalystsAr: `الترقيات التقنية وتكاملات المطورين والمؤسسات في منظومة ${s.name}.`,
      risksEn: "Crypto market cyclicality and execution delays.",
